const router = require('express').Router();
const { autorizarPermiso: permiso } = require('../middleware/auth');
const { requireFeature } = require('../middleware/plan');
const c = require('../controllers/te-controller');
router.use(requireFeature('programaTransferencia', { codigoDenegado: 'PLAN_UPGRADE_REQUIRED' }));
const ver = permiso('reproduccion.ver'), gestionar = permiso('reproduccion.gestionar'), diagnosticar = permiso('reproduccion.iatfDiagnosticar');
router.get('/colectas', ver, c.colectas);
router.post('/colectas', gestionar, c.crearColecta);
router.post('/colectas/:id/finalizar', gestionar, c.finalizarColecta);
router.post('/colectas/:id/pasos/:pasoId/ejecutar', gestionar, c.ejecutarDonante);
router.get('/banco', ver, c.banco);
router.get('/banco/:id', ver, c.detalle);
router.post('/banco/compras', gestionar, c.compra);
router.post('/banco/:id/traslados', gestionar, c.trasladar);
router.post('/banco/:id/mermas', gestionar, c.merma);
router.get('/campanas', ver, c.campanas);
router.post('/campanas', gestionar, c.crearCampana);
router.post('/campanas/:id/pasos/:pasoId/ejecutar', gestionar, c.ejecutarPaso);
router.post('/campanas/:id/receptoras/:animalId/evaluacion', diagnosticar, c.evaluar);
router.post('/campanas/:id/receptoras/:animalId/transferir', gestionar, c.transferir);
router.post('/campanas/:id/receptoras/:animalId/diagnosticos', diagnosticar, c.diagnosticar);
router.post('/campanas/:id/asignaciones', gestionar, c.asignar);
router.post('/campanas/:id/cerrar', gestionar, c.cerrar);
router.get('/indicadores', permiso('reportes.ver'), c.indicadores);
module.exports = router;
